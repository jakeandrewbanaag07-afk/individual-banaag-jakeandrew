package com.joysistvi.day3.variables;

public class Variables {


    public static void main(String[] args) {

        boolean isStudent = true;
        byte age = 19;
        short year = 2026;
        int number = 1000;
        long population = 1000000L;
        float grade = 95.5f;
        double price = 150.75;
        char middleInitial = 'A';
        String firstName = "Jake Andrew";
        String lastName = "Banaag";

        System.out.println("Full Name: " + lastName + ", " + firstName + " " + middleInitial + ".");
        System.out.println("Boolean: " + isStudent);
        System.out.println("Byte: " + age);
        System.out.println("Short: " + year);
        System.out.println("Int: " + number);
        System.out.println("Long: " + population);
        System.out.println("Float: " + grade);
        System.out.println("Double: " + price);

    }
}

